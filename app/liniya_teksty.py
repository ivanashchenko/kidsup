# Подстановки, которые сами — целые предложения (из словарей выше).
CELYE = ("pervoe_zanyatie", "mesto", "vopros_uroven")

_PH = re.compile(r"\{([a-z_]+)\}")
# Граница предложения: пробел после точки, вопроса, восклицания — и после
# подстановок из CELYE: каждая сама целое предложение.
_PREDLOZHENIE = re.compile("|".join([r"(?<=[.!?…])\s+"]
                                    + [r"(?<=\{%s\})\s+" % k for k in CELYE]))


def zapolnit(tekst: str, ctx: dict) -> str:
    """Подставить данные; предложение с пустой подстановкой убрать целиком."""
    out = []
    for s in _PREDLOZHENIE.split(tekst or ""):
        imena = _PH.findall(s)
        if any(n in ctx and not str(ctx[n] if ctx[n] is not None else "").strip() for n in imena):
            continue
        out.append(_PH.sub(lambda m: str(ctx[m.group(1)]) if m.group(1) in ctx else m.group(0), s))
    return " ".join(x for x in out if x.strip()).strip()


def pervoe_zanyatie(vid: str, ctx: dict) -> str:
    """Фраза про первое занятие для направления: obychnoe / sad / platnoe."""
    return zapolnit(PERVOE_ZANYATIE.get(vid) or PERVOE_ZANYATIE["obychnoe"], ctx)


def otvety(ctx: dict, klyuchi=None) -> dict:
    """Все ответы с подстановкой: {ключ: {knopka, otvet, shag, pomni}}.
    В ctx от страницы, кроме подстановок: vid_pervogo (вид первого занятия),
    mesto_vid (est / po_dnyam / list — что известно о местах) и predmet
    выбранной группы; группы нет — gruppa пустая."""
    ctx = dict(ctx)
    s_gruppoj = bool(str(ctx.get("gruppa") or "").strip())
    vid = ctx.get("vid_pervogo") or "obychnoe"
    if "pervoe_zanyatie" not in ctx:
        ctx["pervoe_zanyatie"] = pervoe_zanyatie(vid, ctx)
    if "mesto" not in ctx:
        shablon = MESTO.get(ctx.get("mesto_vid") or "") if s_gruppoj else None
        ctx["mesto"] = zapolnit(shablon, ctx) if shablon else ""
    if "vopros_uroven" not in ctx:
        ctx["vopros_uroven"] = VOPROS_UROVEN.get(ctx.get("predmet") or "", "") if s_gruppoj else ""
    res = {}
    for k in (klyuchi or OTVETY):
        o = OTVETY[k]
        tekst = o["otvet"]
        if s_gruppoj and o.get("otvet_po_vidu"):
            tekst = o["otvet_po_vidu"].get(vid) or tekst
        res[k] = {"knopka": o["knopka"], "otvet": zapolnit(tekst, ctx),
                  "shag": zapolnit(o.get("shag", ""), ctx),
                  "pomni": zapolnit(o.get("pomni", ""), ctx)}
    return res
