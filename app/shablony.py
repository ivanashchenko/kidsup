SECTIONS = [("0", "По возрасту — первое касание"), ("1", "По предметам"),
            ("2", "Организационное"), ("3", "События набора"),
            ("4", "Ответы на сомнения")]


def main():
    from pathlib import Path
    rows = build()
    out = [f"<style>{CSS}</style>", "<h1>Шаблоны Wazzup — быстрые ответы админов</h1>",
           "<div class=sub>Скопировать в кабинет Wazzup → Шаблоны сообщений: "
           "название — как в заголовке карточки (цифры дают порядок и быстрый "
           "поиск), тег — рядом. Старые шаблоны после переноса пометить тегом "
           "«архив» или удалить. Цены из единого прайса, действительны для "
           "сезона 2026/27.</div>"]
    for prefix, title in SECTIONS:
        out.append(f"<h2>{title}</h2>")
        for name, tag, text in rows:
            if name.startswith(prefix):
                out.append(f"<div class=card><div class=nm>{_html.escape(name)}"
                           f"<span class=tg>тег: {_html.escape(tag)}</span></div>"
                           f"<pre>{_html.escape(text)}</pre></div>")
    p = Path(__file__).resolve().parent.parent / "docs" / "shablony_wazzup.html"
    p.write_text("\n".join(out), encoding="utf-8")
    print(f"{p}: {len(rows)} шаблонов")


if __name__ == "__main__":
    main()
