def _plural(n: int, one: str, few: str, many: str) -> str:
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return one
    if 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        return few
    return many


def facts(groups: list[dict]) -> dict:
    """Что сейчас правда про набор — из этих чисел собираются все тексты."""
    real = [g for g in groups if not g.get("buffer")]
    free_total = sum(g["free"] for g in real)
    by_course: dict[str, dict] = {}
    for g in real:
        c = by_course.setdefault(g["course"], {"course": g["course"], "free": 0,
                                               "groups": 0, "price": g.get("price_new"),
                                               "price_label": g.get("price_label"),
                                               "ages": [], "slots": []})
        c["free"] += g["free"]
        c["groups"] += 1
        if g.get("age_lo"):
            c["ages"] += [g["age_lo"], g["age_hi"]]
        if g["free"] > 0 and g["time"] != "—":
            c["slots"].append(f"{g['day']} {g['time']}")
    for c in by_course.values():
        c["age"] = (f"{min(c['ages']):g}–{max(c['ages']):g} лет" if c["ages"] else "")
        c["slots"] = c["slots"][:3]
    # индивидуальные слоты (логопед) не считаем дефицитом: там всегда «1 место»,
    # и в рассылке это выглядит как искусственный ажиотаж
    scarce = sorted([g for g in real if 0 < g["free"] <= 3 and g["capacity"] >= 4],
                    key=lambda g: g["free"])[:6]
    days_left = (date(2026, 9, 30) - date.today()).days
    return {
        "free_total": free_total,
        "by_course": sorted(by_course.values(), key=lambda c: -c["free"]),
        "scarce": scarce,
        "days_left": max(0, days_left),
    }


def _course_lines(f: dict, limit: int = 7) -> str:
    out = []
    for c in f["by_course"][:limit]:
        if not c["free"]:
            continue
        # подпись берём из прайса: у сада это посещения, у логопеда — консультация,
        # писать всем «за 8 занятий» было бы враньём
        price = ""
        if c.get("price"):
            label = (c.get("price_label") or "").strip()
            price = f" — {c['price']:,} ₽".replace(",", " ")
            if label:
                price += f" / {label[0].lower() + label[1:]}"
        out.append(f"• {c['course']}{(' ' + c['age']) if c['age'] else ''}{price}")
    return "\n".join(out)


def _scarce_lines(f: dict) -> str:
    out = []
    for g in f["scarce"]:
        word = _plural(g["free"], "место", "места", "мест")
        out.append(f"• {g['course']}, {g['day']} в {g['time']}"
                   f"{(' (' + g['age'] + ')') if g['age'] != '—' else ''} — "
                   f"осталось {g['free']} {word}")
    return "\n".join(out)


