"""Подсказка для звонка: что сказать, а не только что знать.

Разбор двух версий, которые лежат в карточках рядом (сравнение 21.08).

Версия 10.08 — «Возраст. Сегмент: А, ходили летом 2026. Посещал: английский
летний клуб. Предлагать в первую очередь: нулевой класс или подготовка
к школе. Вторым предметом: менталка, скорочтение, каллиграфия. Аргумент:
ребёнок уже у нас, летом был в англ. клубе — прямая дорога в постоянную
группу».

Версия 16.08 — «Возраст на 1 сентября. Ходил: английский летний клуб
(1 зан., до 13.07). На 2026/27 не записан. Предложить: ПШ1 + английский
A1 Movers (вт-чт 19:00). Первое занятие условно-бесплатное. События».

Первая сильнее по трём причинам, и это не вкусовщина.

  1. В ней есть АРГУМЕНТ — единственная строка, которая говорит, ЧТО СКАЗАТЬ,
     чтобы человек согласился. Всё остальное в обеих версиях — факты, а факты
     сами по себе не продают. Во второй версии аргумента нет вовсе: админ
     дочитывает до конца и всё равно не знает, с чего начать разговор.
  2. В ней есть ИЕРАРХИЯ: «в первую очередь» и «вторым предметом». Это
     структура продажи — главный продукт плюс допродажа. Во второй версии два
     предмета через плюс: админ либо вываливает оба сразу, либо выбирает
     наугад. А скидка 10% на второй предмет работает только тогда, когда
     второй предмет вообще предложили.
  3. В ней есть СЕГМЕНТ — объяснение, почему подсказка именно такая. С ним
     админ понимает логику и может от неё отступить, когда разговор идёт
     иначе. Без него подсказка — чёрный ящик, которому надо верить.

Чего не хватало обеим и что добавлено здесь (по решению Бориса 21.08):

  · ДИАГНОСТИКА НА ПЕРВОМ ЗАНЯТИИ. Это меняет смысл приглашения. Пока мы
    зовём «посмотреть», родитель приходит нас оценивать — и сравнивать
    с другими. Когда мы говорим «педагог посмотрит, что у ребёнка уже хорошо,
    что стоит подтянуть, и скажет, как наши занятия с этим помогут», родитель
    идёт за экспертным мнением о своём ребёнке. Это то, за чем он и так ходит
    к специалистам, только у нас бесплатно. И это же — фиксация стартового
    уровня, без которой не действует гарантия чтения.
  · ТРИ СОБЫТИЯ вместо одного. Праздник, День открытых дверей и Неделя
    открытых уроков — разные поводы для разных людей: кому-то проще прийти
    с ребёнком на праздник в парк, кому-то нужен именно урок.

Подсказка живёт комментарием в карточке — там нет лимита в 250 символов,
поэтому она может быть подробной. Задача остаётся короткой.
"""

from __future__ import annotations

import logging
from datetime import date

log = logging.getLogger("kidsup.hint")

SEASON = date(2026, 9, 1)
# МойКласс режет комментарий: 1572 символа дают HTTP 500, 1000 проходит.
LIMIT = 995

EVENTS = ("29.08 сб — праздник открытия сезона; 30.08 вс — День открытых "
          "дверей; 31.08–06.09 — Неделя открытых уроков. Занятия с 31.08.")

# МойКласс режет комментарий примерно на 1000 символах (проверено 21.08:
# 1572 даёт HTTP 500, 1000 проходит), поэтому подсказка пишется плотно.
TRIAL = (
    "Первое занятие условно-бесплатное: не понравится — не платит, понравится — "
    "входит в абонемент. И главное: на нём педагог проведёт ДИАГНОСТИКУ — "
    "скажет, что у ребёнка уже хорошо, что стоит подтянуть и как наши занятия "
    "с этим помогут. Родитель уходит с пониманием, а не «посмотрели»."
)

# Главное предложение и допродажа по возрасту на 1 сентября.
BY_AGE = [
    (3.0, "музыка и речь или раннее развитие, первый уровень (вместе с мамой)",
          "ИЗО"),
    (4.2, "раннее развитие второго уровня или английский детский сад",
          "ИЗО, музыка и речь"),
    (5.5, "подготовка к школе ПШ1 (нечитающие)",
          "английский Starters, ментальная арифметика, шахматы"),
    (7.3, "нулевой класс (полный день) или подготовка к школе по чтению — "
          "ПШ1 нечитающие / ПШ2 читающие",
          "английский по уровню, ментальная арифметика, шахматы"),
    (99.0, "английский по уровню Cambridge",
           "ментальная арифметика, скорочтение, шахматы, ИЗО"),
]

# Сегмент объясняет, почему подсказка такая, и задаёт аргумент разговора.
# Формы даны в мужском и женском роде: «София был у нас» читается как
# небрежность, а подсказку админ произносит вслух почти дословно.
SEGMENTS = {
    "лето": ("A — был у нас этим летом",
             "{child} {был} у нас совсем недавно, летом. {Ему} не надо привыкать "
             "заново — {он} уже знает центр и педагогов, это прямая дорога "
             "в постоянную группу"),
    "год": ("B — занимался в прошлом учебном году",
            "{child} {занимался} у нас в прошлом году. Мы знаем, как {он} "
            "работает и что {ему} даётся, — начинать с нуля не придётся"),
    "давно": ("C — занимался раньше, больше года назад",
              "{child} у нас уже {занимался}. С тех пор {он} {подрос}, и по "
              "возрасту {ему} подходит уже другое — есть о чём поговорить"),
    "новый": ("D — новый контакт",
              "Позвонить и познакомиться: рассказать, что подходит "
              "{child} по возрасту"),
}

# Мужские имена, оканчивающиеся на -а/-я: без списка «Никита» станет девочкой.
_MALE_A = {"никита", "илья", "данила", "данил", "савва", "лука", "кузьма",
           "фома", "миша", "гоша", "лёва", "лева", "серёжа", "сережа",
           "паша", "саша", "женя", "валя", "слава", "дима", "сеня",
           "коля", "толя", "витя", "петя", "вася", "юра", "боря",
           "гриша", "тёма", "тема", "рома", "костя", "митя", "стёпа",
           "степа", "сева", "кирюша", "ваня"}


def is_female(name: str) -> bool:
    """Пол по имени. Не идеально, но «София был» хуже редкой ошибки."""
    n = (name or "").strip().lower()
    if not n:
        return False
    if n in _MALE_A:
        return False
    return n.endswith(("а", "я"))


def _forms(female: bool) -> dict:
    return {
        "был": "была" if female else "был",
        "занимался": "занималась" if female else "занимался",
        "подрос": "подросла" if female else "подрос",
        "Ему": "Ей" if female else "Ему",
        "ему": "ей" if female else "ему",
        "он": "она" if female else "он",
    }


def age_on_season(birthday: str | None) -> float | None:
    if not birthday:
        return None
    try:
        return round((SEASON - date.fromisoformat(birthday[:10])).days / 365.25, 1)
    except ValueError:
        return None


def offer_for(age: float | None) -> tuple[str, str]:
    """(главное предложение, чем добрать вторым предметом)."""
    if age is None:
        return ("уточнить возраст — от него зависит всё остальное",
                "подобрать после того, как выяснили возраст")
    for edge, main, second in BY_AGE:
        if age < edge:
            return main, second
    return BY_AGE[-1][1], BY_AGE[-1][2]


def segment_of(last_visit: str | None) -> str:
    if not last_visit:
        return "новый"
    if last_visit >= "2026-06-01":
        return "лето"
    if last_visit >= "2025-09-01":
        return "год"
    return "давно"


def _month_ru(d: str) -> str:
    M = ["января", "февраля", "марта", "апреля", "мая", "июня",
         "июля", "августа", "сентября", "октября", "ноября", "декабря"]
    try:
        dt = date.fromisoformat(d[:10])
        return f"{dt.day} {M[dt.month - 1]}"
    except Exception:
        return d[:10]


def first_name(full: str) -> str:
    """Имя для разговора. В карточках формат «Фамилия Имя», поэтому берём
    второе слово: администратор говорит «Владимир», а не «Карнажицкий
    Владимир» — иначе звучит как из поликлиники."""
    parts = [w for w in (full or "").split("(")[0].split() if w]
    if len(parts) >= 2 and parts[1][:1].isupper():
        return parts[1]
    return parts[0] if parts else "ребёнок"


def _years(age: float) -> str:
    """«6,2 года», «5 лет», «1 год» — по-русски, с запятой.

    Дробное число всегда тянет родительный падеж единственного числа:
    «6,2 года», а не «6,2 лет» — как «6,2 секунды», а не «секунд»."""
    if abs(age - round(age)) > 0.05:
        return f"{age:g}".replace(".", ",") + " года"
    whole = int(round(age))
    tail = whole % 10
    if 11 <= whole % 100 <= 14 or tail == 0 or tail >= 5:
        word = "лет"
    elif tail == 1:
        word = "год"
    else:
        word = "года"
    return f"{whole} {word}"


def build(child: str, birthday: str | None = None, was: list[str] | None = None,
          last_visit: str | None = None, enrolled: list[str] | None = None,
          group_time: str | None = None) -> str:
    """Подсказка целиком. Кладётся комментарием в карточку."""
    full = (child or "ребёнок").split("(")[0].strip() or "ребёнок"
    name = first_name(full)
    age = age_on_season(birthday)
    main, second = offer_for(age)
    seg_key = segment_of(last_visit)
    seg_name, arg_tpl = SEGMENTS[seg_key]
    arg = arg_tpl.format(child=name, **_forms(is_female(name)))

    facts = [f"{full}, {_years(age)} на 1 сентября" if age else full]
    if was:
        facts.append(("ходила на " if is_female(name) else "ходил на ")
                     + ", ".join(sorted(set(was))[:3]))
    if last_visit:
        facts.append("последний раз " + _month_ru(last_visit))
    facts.append("на 2026/27 " + ("записан — " + enrolled[0][:40]
                                  if enrolled else "НЕ записан"))

    lines = [
        f"🎯 ПОДСКАЗКА ДЛЯ ЗВОНКА · сегмент {seg_name}",
        "КТО: " + "; ".join(facts) + ".",
        "",
        f"С ЧЕГО НАЧАТЬ: {arg}.",
        "",
        f"ГЛАВНОЕ: {main}" + (f" ({group_time})" if group_time else "") + ".",
        f"ВТОРЫМ ПРЕДМЕТОМ (−10%): {second}.",
        "",
        f"ЗВАТЬ НА ВСЕ ТРИ: {EVENTS}",
        "",
        TRIAL,
    ]
    tail = "\nДо 30.08 сентябрь по ценам прошлого года; скидки не суммируются."
    guarantee = ("\n\nГАРАНТИЯ ЧТЕНИЯ: с нуля читает трёхбуквенные слова "
                 "за 3 месяца, иначе занимается бесплатно, пока не зачитает. "
                 "Условия назвать сразу: диагностика на первом занятии, "
                 "посещаемость от 80%, домашние задания.")
    text = "\n".join(lines)
    # Гарантия — важная, но добавляем только если влезает целиком: обрубок
    # посреди слова читается как сбой и подрывает доверие ко всей подсказке.
    if age and 4.5 <= age <= 7.5 and not enrolled and \
            len(text) + len(guarantee) + len(tail) <= LIMIT:
        text += guarantee
    if len(text) + len(tail) <= LIMIT:
        text += tail
    return text


def short(child: str, birthday: str | None = None, was: list[str] | None = None,
          last_visit: str | None = None, tried: str = "") -> str:
    """Короткая строка для тела задачи — там лимит 250 символов."""
    full = (child or "").split("(")[0].strip()
    age = age_on_season(birthday)
    main, _ = offer_for(age)
    seg = segment_of(last_visit)
    when = {"лето": "был летом", "год": "ходил в прошлом году",
            "давно": "занимался давно", "новый": "новый контакт"}[seg]
    head = full + (f", {_years(age)}" if age else "")
    body = (f"📞 {head} — {when}"
            + (f" ({', '.join(sorted(set(was))[:2])})" if was else "")
            + f". Предложить: {main.split(' или ')[0]}. "
            + (tried + " " if tried else "")
            + "Звать на 29.08, 30.08 и Неделю уроков.")
    return body[:250]
