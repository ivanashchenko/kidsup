"""Самопроверка пульта: ищет в живом списке дел то, на что жалуются админы.

22.09.2026. Борис: «Можно уже наконец сделать Пульт без косяков??!!» — обещать
это словами бесполезно: каждый раз, когда я шёл смотреть глазами, находил новое.
Значит смотреть должен не я, а проверка, и каждый час.

Она не чинит — она показывает. Разбор звонков и автопилот дёргают её после
каждого прогона; если проверка что-то нашла, это видно на /api/pult/proverka
и в логе, и чинится в тот же день, а не через неделю по жалобе Лены.

Правила, которые она стережёт, — ровно те, на которые жаловались:
  дубли на одну семью, пункты без действия, пункты не тому человеку,
  пункты, которых никто не увидит, обрывки текста, запрещённые формулировки.
"""
from __future__ import annotations

import re

from . import db

# Кто вообще может увидеть колонку. Пункт, адресованный кому-то ещё,
# физически не показывается ни на одной странице — он потерян.
KOLONKI = {"Аня", "Лена", "Ира", "Лиза", "Борис"}

# С 20.09 (решение владельца) Лиза закрывает занятия и работает с долгами.
# Всё остальное ей ставить нельзя — это чужая работа, которую она не сделает.
LIZA_MOZHNO = re.compile(
    r"занят|явк|провед|посещ|долг|задолж|списа|абонемент|оплач|не оплач|"
    r"возврат денег|вернуть деньги|возврат остатка|реквизит", re.I)

# Формулировки, запрещённые брендом. «Бесплатное пробное занятие» обещает
# бесплатно — у нас первое занятие условно-бесплатное, и это разные обещания
# родителю. А вот «бесплатный пробный ДЕНЬ» у мини-сада и нулевого класса —
# наша собственная формулировка, её трогать нельзя: 22.09 первая версия этой
# проверки подняла 17 тревог, и все семнадцать были про законный пробный день.
# Различаем по роду, а не по соседним словам: «занятие» среднего рода, и
# запрещено именно «бесплатноЕ пробноЕ». «Бесплатный пробный ДЕНЬ» (мужской)
# и «бесплатная пробная НЕДЕЛЯ» (женский) — наши законные формулировки.
ZAPRESHCHENO = re.compile(
    r"бесплатн(ое|ого|ому|ым|ом)\s+пробн(ое|ого|ому|ым|ом)|"
    r"бесплатн\w+\s+пробн\w+\s+заняти", re.I)


def _zapret(tekst: str):
    """Нашлось ли запрещённое «бесплатное пробное занятие»."""
    return ZAPRESHCHENO.search(tekst or "")

# Пункт, по которому нечего делать: мы сами написали «действий не требуется»
# или модель не поняла сообщение и честно написала «непонятно».
PUSTYSHKA = re.compile(
    r"действий не требуется|не требует действий|\[непонятно\]|"
    r"^\s*(тест|проверка)\s*$", re.I)

LIMITY = (250, 400)          # на такие длины режут текст генераторы


def _p10(x) -> str:
    d = "".join(c for c in str(x or "") if c.isdigit())
    return d[-10:] if len(d) >= 10 else ""


def _stroki(day: str) -> list[dict]:
    """Все строки инбокса за день + задачи смены, приведённые к одному виду."""
    from . import pult
    out: list[dict] = []
    try:
        with db.get_conn() as conn:
            rows = conn.execute(
                "SELECT id, ts, who, text, phone, source, done FROM plan_inbox "
                "WHERE day=? ORDER BY id", (day,)).fetchall()
    except Exception:
        rows = []
    for r in rows:
        out.append({"вид": "пункт", "id": r["id"], "кто": r["who"] or "",
                    "текст": r["text"] or "", "телефон": _p10(r["phone"]),
                    "источник": r["source"] or "", "закрыт": bool(r["done"]),
                    "время": (r["ts"] or "")[11:16]})
    try:
        for who, items in (pult.tasks(day) or {}).items():
            for it in items:
                out.append({"вид": "задача", "id": it.get("id"), "кто": who,
                            "текст": it.get("text") or "", "телефон": "",
                            "источник": "смена", "закрыт": bool(it.get("done")),
                            "время": it.get("t") or ""})
    except Exception:
        pass
    # у задач смены телефон живёт внутри текста
    for s in out:
        if not s["телефон"]:
            m = re.search(r"\b[78]?(9\d{9})\b", s["текст"])
            if m:
                s["телефон"] = m.group(1)
    return out


def _shablony() -> list[tuple[str, int, str]]:
    """Страницы, где запрещённая формулировка ещё жива. Строку с самим
    правилом («слов „бесплатное пробное“ не используем») не считаем."""
    import pathlib
    koren = pathlib.Path(__file__).resolve().parent
    out: list[tuple[str, int, str]] = []
    for papka, maska in ((koren / "templates", "*.html"),
                         (koren / "static", "*.html")):
        if not papka.is_dir():
            continue
        for f in sorted(papka.glob(maska)):
            try:
                tekst = f.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            for n, stroka in enumerate(tekst.splitlines(), 1):
                if _zapret(stroka) and "не используем" not in stroka:
                    out.append((f"{papka.name}/{f.name}", n, stroka.strip()))
    return out


def _hvost(day: str) -> dict:
    """Сколько незакрытых дел осталось с прошлых дней и у кого."""
    try:
        with db.get_conn() as conn:
            rows = conn.execute(
                "SELECT who, COUNT(*), MIN(day) FROM plan_inbox "
                "WHERE done=0 AND day<? GROUP BY who", (day,)).fetchall()
    except Exception:
        return {"всего": 0, "по людям": {}, "самое старое": ""}
    po = {(r[0] or "—"): r[1] for r in rows}
    return {"всего": sum(po.values()), "по людям": po,
            "самое старое": min((r[2] or "" for r in rows), default="")}


def proverit(day: str = "") -> dict:
    """Что сегодня не так с пультом. Только чтение."""
    from . import pult
    day = day or pult.today()
    stroki = _stroki(day)
    otkrytye = [s for s in stroki if not s["закрыт"]]
    bedy: list[dict] = []

    def _beda(rod: str, chto: str, gde: str, pochemu: str) -> None:
        bedy.append({"род": rod, "что": chto, "где": gde, "почему": pochemu})

    # 1. Две строки про одну семью открыты одновременно. Админ закроет одну,
    #    вторая останется висеть и будет выглядеть бессмысленной — ровно то,
    #    на что жаловалась Лена 22.09 (Афанасьева, Панишева, Сорокина).
    #    Считаем по паре «человек + семья»: два пункта про одну семью у РАЗНЫХ
    #    людей — это обычное разделение работы (Борис даёт цену, Лена её
    #    отправляет; Аня встречает ребёнка, Лена говорит с родителем на
    #    выходе). Дубль — когда одному человеку про одну семью висит два дела.
    po_nomeru: dict[tuple[str, str], list[dict]] = {}
    for s in otkrytye:
        if s["телефон"]:
            po_nomeru.setdefault((s["кто"], s["телефон"]), []).append(s)
    for (kto, ph), gruppa in po_nomeru.items():
        if len(gruppa) > 1:
            _beda("дубли", f"у {kto or '—'} {len(gruppa)} открытых строки на номер {ph}",
                  ", ".join(f"{g['вид']} {g['id']} ({g['источник']})" for g in gruppa),
                  "закроет одну, остальные останутся висеть без смысла")

    # 2. Пункт, по которому делать нечего.
    for s in otkrytye:
        if PUSTYSHKA.search(s["текст"]):
            _beda("пустышка", s["текст"][:80], f"{s['вид']} {s['id']} ({s['кто']})",
                  "нет действия — админ тратит время, чтобы понять, что делать нечего")

    # 3. Пункт, которого никто не увидит: адресат не из колонок пульта.
    for s in stroki:
        if s["вид"] == "пункт" and s["кто"] not in KOLONKI:
            _beda("потерян", f"адресат «{s['кто'] or 'пусто'}»", f"пункт {s['id']}",
                  "такой колонки на странице нет — строка не показывается никому")

    # 4. Лизе — только закрытие занятий и долги (решение владельца 20.09).
    for s in otkrytye:
        if s["кто"] == "Лиза" and not LIZA_MOZHNO.search(s["текст"]):
            _beda("не тому", s["текст"][:80], f"{s['вид']} {s['id']}",
                  "Лиза с 20.09 занимается только явкой и долгами")

    # 5. Запрещённая формулировка уходит админу как готовая фраза родителю.
    for s in stroki:
        if _zapret(s["текст"]):
            _beda("формулировка", s["текст"][:80], f"{s['вид']} {s['id']} ({s['кто']})",
                  "у нас условно-бесплатное первое занятие, а не бесплатное пробное")

    # 6. Текст обрезан ровно по лимиту — значит оборван на полуслове и
    #    последнее указание админ не прочитает.
    #    Смотрим диапазон, а не точное совпадение: после strip длина могла
    #    стать 399 или 249, и сторож слепнул (22.09, аудит самой проверки).
    for s in otkrytye:
        t = s["текст"].rstrip()
        if any(abs(len(t) - L) <= 3 for L in LIMITY) and not t.endswith((".", "!", "?", "»", "…")):
            _beda("обрыв", t[-40:], f"{s['вид']} {s['id']} ({s['кто']})",
                  f"текст упёрся в лимит ({len(t)} символов) и оборван на полуслове")

    # 7. Перегруз: строк больше, чем физически успеть до 20:00.
    po_lyudyam: dict[str, int] = {}
    for s in otkrytye:
        po_lyudyam[s["кто"]] = po_lyudyam.get(s["кто"], 0) + 1
    for kto, n in po_lyudyam.items():
        if kto in ("Аня", "Лена", "Ира") and n > 25:
            _beda("перегруз", f"{kto}: {n} открытых строк", "колонка",
                  "за смену столько не делается — список перестаёт быть планом")

    # 8. Телефон есть, но это не мобильный семьи (групповой чат, короткий
    #    номер, рабочая линия) — админ позвонит в пустоту.
    for s in otkrytye:
        if s["вид"] == "пункт" and s["телефон"] and not s["телефон"].startswith("9"):
            _beda("телефон", s["телефон"], f"пункт {s['id']} ({s['кто']})",
                  "это не мобильный семьи — звонок уйдёт не туда")

    # 9. Запрещённая формулировка в кнопках «скопировать клиенту». 22.09 их
    #    нашлось три штуки: админ жал кнопку и обещал родителю «бесплатное
    #    пробное», а на стойке выяснялось, что занятие входит в абонемент.
    #    Поэтому смотрим не только инбокс, но и шаблоны страниц.
    for fajl, nomer, stroka in _shablony():
        _beda("формулировка", stroka[:90], f"{fajl}:{nomer}",
              "кнопка вставит родителю обещание «бесплатно» — у нас условно-бесплатное")

    # 10. Хвост прошлых дней. До 22.09 незакрытый пункт в полночь просто
    #     исчезал с глаз, и хвост копился незаметно: на 22.09 его оказалось
    #     529 штук с 03.09 — три недели обещаний семьям, которых никто не
    #     видел. Теперь он виден в колонке отдельным блоком, а его размер —
    #     здесь, чтобы владелец знал цифру без раскопок.
    hvost = _hvost(day)
    if hvost["всего"] > 50:
        _beda("хвост", f"{hvost['всего']} незакрытых дел прошлых дней "
                       f"(с {hvost['самое старое']})", "все колонки",
              "это обещания семьям, которые мы не выполнили и не отменили")

    svodka = {
        "день": day, "всего строк": len(stroki), "открытых": len(otkrytye),
        "хвост прошлых дней": hvost,
        "по людям": po_lyudyam,
        "бед": len(bedy),
        "по родам": {r: sum(1 for b in bedy if b["род"] == r)
                     for r in sorted({b["род"] for b in bedy})},
    }
    return {"ok": not bedy, **svodka, "беды": bedy}


def kratko(day: str = "") -> str:
    """Одна строка для лога автопилота."""
    r = proverit(day)
    if r["ok"]:
        return f"пульт чист: {r['открытых']} открытых строк, бед нет"
    rody = ", ".join(f"{k} {v}" for k, v in r["по родам"].items())
    return f"пульт: {r['бед']} бед ({rody}) при {r['открытых']} открытых строках"
